export function translate(language, text, values = {}) {
  const translations = TRANSLATIONS[language];
  let translated = language === 'en' ? text : translations?.[text];
  let replacements = values;

  if (!translated && translations) {
    const matchingTemplate = Object.keys(translations).find((template) => {
      if (!template.includes('{')) return false;
      const pattern = template
        .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        .replace(/\\\{(\w+)\\\}/g, '(.+?)');
      return new RegExp(`^${pattern}$`).test(text);
    });
    if (matchingTemplate) {
      const pattern = matchingTemplate
        .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        .replace(/\\\{(\w+)\\\}/g, '(.+?)');
      const match = text.match(new RegExp(`^${pattern}$`));
      const keys = [...matchingTemplate.matchAll(/\{(\w+)\}/g)].map((item) => item[1]);
      replacements = { ...values, ...Object.fromEntries(keys.map((key, index) => [key, match[index + 1]])) };
      translated = translations[matchingTemplate];
    }
  }

  return (translated ?? text).replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(replacements, key) ? replacements[key] : match
  ));
}

export function translateCurrent(text, values) {
  const language = useSettingsStore.getState().language ?? useSettingsStore.getState().guideLanguage ?? 'en';
  return translate(language, text, values);
}

export function useTranslation() {
  const language = useSettingsStore((state) => state.language ?? state.guideLanguage ?? 'en');
  return {
    language,
    t: (text, values) => translate(language, text, values),
  };
}
